"""Loads Montgomery County's 14 official early voting centers for the 2026
general election into polling_locations. Source: MSBE PDF (Montgomery County
section, "14 centers"):
https://elections.maryland.gov/elections/2026/2026_Early_Voting_Centers-GG-EN.pdf

The list is identical to the primary's (same names and addresses -- checked
programmatically against the PDF text on 2026-10-20), so CENTERS is reused
from the primary loader, and each center's point is copied from its
already-geocoded primary row instead of geocoding the same address again.
Only the dates change: Oct 22-29, 7 am - 8 pm.

Usage:
    python3 scripts/load_montgomery_early_voting_2026_general.py > out.sql
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from load_montgomery_early_voting_2026_primary import (  # noqa: E402
    CENTERS,
    PRIMARY_ELECTION_ID,
    dq,
    sql_text,
)

SOURCE_URL = "https://elections.maryland.gov/elections/2026/2026_Early_Voting_Centers-GG-EN.pdf"
SOURCE_ID = "cccccccc-cccc-cccc-cccc-cccccccccccc"
GENERAL_ELECTION_ID = "55555555-5555-5555-5555-555555555555"


def main():
    out = sys.stdout
    out.write("-- Generated by scripts/load_montgomery_early_voting_2026_general.py. Idempotent: safe to re-run.\n\n")

    out.write(
        "insert into sources (source_id, source_url, source_type, effective_date, confidence, notes)\n"
        f"values ('{SOURCE_ID}', {sql_text(SOURCE_URL)}, {sql_text('early_voting_centers_pdf')}, "
        f"'2026-08-03', 1.0, {sql_text('MSBE early voting centers, 2026 general election, Montgomery County section')})\n"
        "on conflict (source_id) do update set fetched_at = now(), effective_date = excluded.effective_date;\n\n"
    )

    for name, street, city, zip5 in CENTERS:
        address_json = json.dumps({"street": street, "city": city, "state": "MD", "zip5": zip5})
        out.write(
            "insert into polling_locations (election_id, location_type, name, address, geom, hours, "
            "start_date, end_date, source_id)\n"
            f"select '{GENERAL_ELECTION_ID}', 'early_vote', {sql_text(name)}, {dq(address_json, 'j')}::jsonb, "
            f"primary_row.geom, {sql_text('7:00 AM - 8:00 PM')}, '2026-10-22', '2026-10-29', '{SOURCE_ID}'\n"
            "from polling_locations primary_row\n"
            f"where primary_row.election_id = '{PRIMARY_ELECTION_ID}' and primary_row.name = {sql_text(name)}\n"
            "and not exists (\n"
            "  select 1 from polling_locations existing\n"
            f"  where existing.election_id = '{GENERAL_ELECTION_ID}' and existing.name = {sql_text(name)}\n"
            ");\n\n"
        )

    out.write(
        "do $check$ begin\n"
        f"  if (select count(*) from polling_locations where election_id = '{GENERAL_ELECTION_ID}'\n"
        f"      and source_id = '{SOURCE_ID}' and geom is not null) <> {len(CENTERS)} then\n"
        f"    raise exception 'expected {len(CENTERS)} geocoded general early voting centers';\n"
        "  end if;\n"
        "end $check$;\n"
    )

    print("Done.", file=sys.stderr)


if __name__ == "__main__":
    main()
