"""Loads registered voters per Maryland precinct into precinct_registration,
from MSBE's 2026 precinct reference (one row per precinct split and party):
https://elections.maryland.gov/elections/2026/GP26_State_Precinct_Reference.xlsx

The ballot_coverage view uses it to measure ballot coverage in voters.
Splits ("01001.1", "01001.1.1") are summed into their precinct
("2400101-001"). Fails loudly (exit 1, no SQL) on an unknown county name or a
statewide total far from MSBE's ~4.3 million registered voters.

Usage:
    python3 scripts/load_md_precinct_registration.py > out.sql
"""
import collections
import io
import os
import sys
import urllib.request

import openpyxl

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from load_md_early_voting_2026_general import COUNTY_FIPS  # noqa: E402
from load_montgomery_early_voting_2026_primary import sql_text  # noqa: E402

SOURCE_URL = "https://elections.maryland.gov/elections/2026/GP26_State_Precinct_Reference.xlsx"
SOURCE_ID = "dddddddd-dddd-dddd-dddd-dddddddddddd"
EFFECTIVE_DATE = "2026-05-12"  # the file's Last-Modified


def fetch_rows():
    req = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "us-district-zipcode-loader/1.0"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        book = openpyxl.load_workbook(io.BytesIO(resp.read()), read_only=True)
    rows = book.worksheets[0].iter_rows(values_only=True)
    header = next(rows)
    col = {name: i for i, name in enumerate(header)}
    for row in rows:
        yield row[col["COUNTY_NAME"]], str(row[col["ED_PRECINCT"]]), row[col["VOTER_COUNT"]] or 0


def main():
    voters = collections.Counter()
    for county, ed_precinct, count in fetch_rows():
        if county not in COUNTY_FIPS:
            print(f"ERROR: unknown county {county!r}", file=sys.stderr)
            sys.exit(1)
        # "1000.1" (Allegany) and "01001.1.1": election district * 1000 + precinct, then split suffixes.
        n = int(ed_precinct.split(".")[0])
        voters[(COUNTY_FIPS[county], f"{n // 1000:02d}-{n % 1000:03d}")] += count
    total = sum(voters.values())
    if not 4_000_000 < total < 4_600_000:
        print(f"ERROR: statewide total {total} is implausible", file=sys.stderr)
        sys.exit(1)
    print(f"{len(voters)} precincts, {total} registered voters.", file=sys.stderr)

    out = sys.stdout
    out.write("-- Generated by scripts/load_md_precinct_registration.py. Idempotent: safe to re-run.\n\n")
    out.write(
        "insert into sources (source_id, source_url, source_type, effective_date, confidence, notes)\n"
        f"values ('{SOURCE_ID}', {sql_text(SOURCE_URL)}, {sql_text('precinct_reference_xlsx')}, "
        f"'{EFFECTIVE_DATE}', 1.0, {sql_text('MSBE 2026 precinct reference: registered voters per precinct split and party')})\n"
        "on conflict (source_id) do update set fetched_at = now(), effective_date = excluded.effective_date;\n\n"
        "delete from precinct_registration where state = 'MD';\n\n"
        "insert into precinct_registration (state, county_fips, precinct_code, registered_voters, source_id) values\n"
    )
    out.write(",\n".join(
        f"('MD', '{fips}', '{fips}{code}', {n}, '{SOURCE_ID}')" for (fips, code), n in sorted(voters.items())
    ))
    out.write(";\n")


if __name__ == "__main__":
    main()
