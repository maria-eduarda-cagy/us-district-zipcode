"""Loads Virginia voting precincts for Northern Virginia localities from the
Department of Elections' per-locality GIS files
(https://www.elections.virginia.gov/casting-a-ballot/redistricting/gis/ --
one zipped shapefile per county/city, same schema statewide, edited by ELECT
2026-01-06).

Writes the `va_precincts_elect` PRECINCT layer (district_id = the precinct's
11-digit GEOID, e.g. 51510000204) and mirrors it into `precincts`, so ballot
loaders can link ballot styles to precincts. Like load_district_layers.py,
each locality is a mirror of its source: precincts it no longer publishes
are deleted (cascading to their ballot styles -- re-run the ballot loaders
afterwards if precincts changed).

Fairfax County is left out: it uses the county's own live layer
(`va_fairfax_precincts`, see load_district_layers.py), which its ballot
loader is keyed to. Loudoun's old county layer (`va_loudoun_precincts`, bare
precinct numbers, no ballots linked) is superseded and dropped, so a Loudoun
address doesn't get two precincts.

Needs `ogr2ogr` (GDAL) on the PATH.

Usage:
    python3 scripts/load_va_precincts.py > out.sql
"""
import json
import subprocess
import sys
import tempfile
import urllib.request

GIS_BASE = "https://www.elections.virginia.gov/media/redistricting/gis/-zip-files/"
LAYER_ID = "va_precincts_elect"
# ELECT file name -> county FIPS
LOCALITIES = {
    "ALEXANDRIA_CITY": "51510",
    "ARLINGTON_COUNTY": "51013",
    "FAIRFAX_CITY": "51600",
    "FALLS_CHURCH_CITY": "51610",
    "LOUDOUN_COUNTY": "51107",
    "MANASSAS_CITY": "51683",
    "MANASSAS_PARK_CITY": "51685",
    "PRINCE_WILLIAM_COUNTY": "51153",
}


def dq(value: str, tag: str = "q") -> str:
    return f"${tag}${value}${tag}$"


def sql_text(value) -> str:
    return "null" if value is None else dq(str(value))


def read_locality(name: str) -> list:
    with tempfile.TemporaryDirectory() as tmp:
        zip_path = f"{tmp}/{name}.zip"
        request = urllib.request.Request(f"{GIS_BASE}{name}.zip", headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request, timeout=120) as resp, open(zip_path, "wb") as f:
            f.write(resp.read())
        out = f"{tmp}/{name}.geojson"
        subprocess.run(["ogr2ogr", "-f", "GeoJSON", "-t_srs", "EPSG:4326", out, f"/vsizip/{zip_path}/{name}.shp"],
                       check=True, capture_output=True)
        with open(out) as f:
            return json.load(f)["features"]


def precinct_name(props) -> str:
    name = (props.get("PrecinctNa") or "").strip()
    number = (props.get("PrecinctFI") or "").strip()
    return f"{number} {name.title()}" if name and not name.isdigit() else f"Precinct {number}"


def main():
    out = sys.stdout
    out.write("-- Generated by scripts/load_va_precincts.py. Idempotent: safe to re-run.\n\n")
    out.write(
        "insert into district_layers (layer_id, layer_type, name, state, jurisdiction, source_url)\n"
        f"values ({sql_text(LAYER_ID)}, 'PRECINCT', 'Virginia Voting Precincts (Department of Elections)', 'VA', "
        f"'Northern Virginia', {sql_text(GIS_BASE)})\n"
        "on conflict (layer_id) do update set name = excluded.name, source_url = excluded.source_url;\n\n"
        "-- Superseded by va_precincts_elect for Loudoun (no ballot styles were linked to it).\n"
        "delete from district_boundaries where layer_id = 'va_loudoun_precincts';\n"
        "delete from district_layers where layer_id = 'va_loudoun_precincts';\n\n"
    )
    for name, fips in LOCALITIES.items():
        print(f"Fetching {name}...", file=sys.stderr)
        features = read_locality(name)
        geoids = []
        for feat in features:
            props = feat["properties"]
            geoid = props.get("GEOID")
            if not geoid or not geoid.startswith(fips) or not feat.get("geometry"):
                raise ValueError(f"{name}: unexpected feature {props}")
            geoids.append(geoid)
            out.write(
                "insert into district_boundaries (layer_id, district_id, district_name, geom, source_url)\n"
                f"values ({sql_text(LAYER_ID)}, {sql_text(geoid)}, {sql_text(precinct_name(props))}, "
                f"st_multi(st_makevalid(st_setsrid(st_geomfromgeojson({dq(json.dumps(feat['geometry']), 'g')}), 4326))), "
                f"{sql_text(f'{GIS_BASE}{name}.zip')})\n"
                "on conflict (layer_id, district_id, effective_from) do update "
                "set geom = excluded.geom, district_name = excluded.district_name;\n\n"
            )
        if len(set(geoids)) != len(geoids):
            raise ValueError(f"{name}: duplicate GEOIDs")
        id_list = ", ".join(sql_text(g) for g in geoids)
        out.write(
            f"delete from district_boundaries where layer_id = {sql_text(LAYER_ID)} "
            f"and district_id like '{fips}%' and district_id <> all (array[{id_list}]);\n\n"
            "insert into precincts (precinct_code, precinct_name, county_fips, state, geom)\n"
            f"select district_id, district_name, '{fips}', 'VA', geom from district_boundaries\n"
            f"where layer_id = {sql_text(LAYER_ID)} and district_id like '{fips}%'\n"
            "on conflict (state, county_fips, precinct_code, effective_from) do update\n"
            "  set precinct_name = excluded.precinct_name, geom = excluded.geom;\n\n"
            f"delete from precincts where state = 'VA' and county_fips = '{fips}' "
            f"and precinct_code <> all (array[{id_list}]);\n\n"
        )
        print(f"  {len(features)} precincts", file=sys.stderr)
    print("Done.", file=sys.stderr)


if __name__ == "__main__":
    main()
